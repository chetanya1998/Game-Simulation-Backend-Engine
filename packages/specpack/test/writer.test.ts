import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { SECTION_BEGIN, SECTION_END, renderSpecPack, type SpecPack } from '@gamex/specpack';
import { LOCK_PATH, UnsafePathError, assertAllowedPath, writeSpecPack } from '../src/node/index.ts';
import { minimalModel, tempRepo } from './helpers.ts';

let pack: SpecPack;
const read = (repo: string, path: string): string => readFileSync(join(repo, path), 'utf8');

beforeAll(() => {
  pack = renderSpecPack(minimalModel(), { playersPerPersona: 10, days: 3 });
}, 60000);

describe('writeSpecPack', () => {
  it('creates the pack, then a second sync changes nothing (idempotent)', () => {
    const repo = tempRepo();
    const first = writeSpecPack(repo, pack);
    expect(first.written).toBe(true);
    expect(first.files.every((f) => f.action === 'create')).toBe(true);
    expect(existsSync(join(repo, LOCK_PATH))).toBe(true);
    const lockBefore = read(repo, LOCK_PATH);
    const second = writeSpecPack(repo, pack);
    expect(second.files.filter((f) => f.action !== 'unchanged' && f.action !== 'skip')).toEqual([]);
    expect(read(repo, LOCK_PATH)).toBe(lockBefore);
  });

  it('preserves existing AGENTS.md content byte-for-byte and replaces only its own section', () => {
    const repo = tempRepo();
    const mine = '# Agents\n\nOur house rules.\r\nKeep tabs\there.\n';
    writeFileSync(join(repo, 'AGENTS.md'), mine);
    writeSpecPack(repo, pack);
    const after = read(repo, 'AGENTS.md');
    expect(after.startsWith(mine)).toBe(true);
    expect(after).toContain(SECTION_BEGIN);
    const tail = '\n## Later\nadded by the team\n';
    writeFileSync(join(repo, 'AGENTS.md'), `${after}${tail}`);
    expect(writeSpecPack(repo, pack).files.find((f) => f.path === 'AGENTS.md')?.action).toBe(
      'unchanged',
    );
    expect(read(repo, 'AGENTS.md').endsWith(tail)).toBe(true);
  });

  it('never touches an existing CLAUDE.md or GEMINI.md', () => {
    const repo = tempRepo();
    writeFileSync(join(repo, 'CLAUDE.md'), 'mine\n');
    const r = writeSpecPack(repo, pack);
    expect(read(repo, 'CLAUDE.md')).toBe('mine\n');
    expect(r.files.find((f) => f.path === 'CLAUDE.md')?.action).toBe('skip');
    expect(r.files.find((f) => f.path === 'GEMINI.md')?.action).toBe('create');
  });

  it('keeps text written inside GAMEX:EDITABLE regions', () => {
    const repo = tempRepo();
    writeSpecPack(repo, pack);
    const rules = read(repo, 'gamex/backend/RULES.md');
    const edited = rules.replace(
      /(<!-- GAMEX:EDITABLE overview -->\n)[\s\S]*?(\n<!-- GAMEX:END-EDITABLE overview -->)/,
      '$1We run on Postgres 16.$2',
    );
    writeFileSync(join(repo, 'gamex/backend/RULES.md'), edited);
    const r = writeSpecPack(repo, pack);
    expect(r.conflicts).toEqual([]);
    expect(read(repo, 'gamex/backend/RULES.md')).toContain('We run on Postgres 16.');
    expect(r.files.find((f) => f.path === 'gamex/backend/RULES.md')?.action).toBe('unchanged');
  });

  it('reports a hand edit of a generated file as a conflict and writes nothing; --force overwrites', () => {
    const repo = tempRepo();
    writeSpecPack(repo, pack);
    writeFileSync(join(repo, 'gamex/balance/economy.json'), '{"hacked": true}\n');
    const changed = renderSpecPack(
      { ...minimalModel(), meta: { ...minimalModel().meta, name: 'Mini 2' } },
      { playersPerPersona: 10, days: 3 },
    );
    const r = writeSpecPack(repo, changed);
    expect(r.written).toBe(false);
    expect(r.conflicts).toEqual([
      {
        path: 'gamex/balance/economy.json',
        action: 'conflict',
        reason: expect.stringContaining('edited by hand') as unknown,
      },
    ]);
    expect(read(repo, 'gamex/README.md')).toContain('— Mini\n');
    const forced = writeSpecPack(repo, changed, { force: true });
    expect(forced.written).toBe(true);
    expect(read(repo, 'gamex/balance/economy.json')).toContain('GENERATED BY GAMEX ENGINE');
    expect(read(repo, 'gamex/README.md')).toContain('— Mini 2');
  });

  it('reports an editing of the managed AGENTS.md section as a conflict', () => {
    const repo = tempRepo();
    writeSpecPack(repo, pack);
    const agents = read(repo, 'AGENTS.md').replace(
      'Never hardcode economy values.',
      'Hardcode whatever.',
    );
    writeFileSync(join(repo, 'AGENTS.md'), agents);
    const changed = renderSpecPack(
      { ...minimalModel(), meta: { ...minimalModel().meta, name: 'Mini 3' } },
      { playersPerPersona: 10, days: 3 },
    );
    expect(writeSpecPack(repo, changed).conflicts.map((c) => c.path)).toEqual(['AGENTS.md']);
    expect(agents).toContain(SECTION_END);
  });

  it('refuses to overwrite a file it did not write', () => {
    const repo = tempRepo();
    mkdirSync(join(repo, 'gamex/backend'), { recursive: true });
    writeFileSync(join(repo, 'gamex/backend/openapi.yaml'), 'openapi: 3.0.0\n');
    const r = writeSpecPack(repo, pack);
    expect(r.written).toBe(false);
    expect(r.conflicts[0]).toMatchObject({
      path: 'gamex/backend/openapi.yaml',
      reason: 'exists but was not written by GameX',
    });
  });

  it('deletes generated files that are no longer produced, unless they were edited', () => {
    const repo = tempRepo();
    writeSpecPack(repo, pack);
    expect(existsSync(join(repo, 'gamex/tests/golden/placement-interstitial.json'))).toBe(true);
    const m = minimalModel();
    m.monetization.placements = m.monetization.placements.filter((p) => p.id !== 'interstitial');
    m.stateMachine.transitions = m.stateMachine.transitions
      .filter((t) => t.id !== 'continue-ad')
      .map((t) => (t.id === 'continue' ? { ...t, guard: undefined } : t));
    m.invariants = m.invariants.filter((i) => i.id !== 'gap');
    m.constants = m.constants.filter((k) => k.id !== 'gap-seconds');
    const smaller = renderSpecPack(m, { playersPerPersona: 10, days: 3 });
    const r = writeSpecPack(repo, smaller);
    expect(r.conflicts).toEqual([]);
    expect(
      r.files.find((f) => f.path === 'gamex/tests/golden/placement-interstitial.json')?.action,
    ).toBe('delete');
    expect(existsSync(join(repo, 'gamex/tests/golden/placement-interstitial.json'))).toBe(false);
  });

  it('writes nothing in a dry run', () => {
    const repo = tempRepo();
    const r = writeSpecPack(repo, pack, { dryRun: true });
    expect(r.written).toBe(false);
    expect(r.files.length).toBeGreaterThan(20);
    expect(existsSync(join(repo, 'gamex'))).toBe(false);
  });

  it('refuses to write through symlinks', () => {
    const repo = tempRepo();
    const outside = tempRepo();
    symlinkSync(outside, join(repo, 'gamex'));
    expect(() => writeSpecPack(repo, pack)).toThrow(UnsafePathError);
    expect(existsSync(join(outside, 'README.md'))).toBe(false);
  });
});

describe('assertAllowedPath', () => {
  it.each(['gamex/README.md', 'gamex/tests/golden/a.json', 'AGENTS.md', 'CLAUDE.md', 'GEMINI.md'])(
    'allows %s',
    (p) => {
      expect(() => {
        assertAllowedPath(p);
      }).not.toThrow();
    },
  );
  it.each([
    'src/index.ts',
    '../outside.md',
    'gamex/../src/x.ts',
    '/etc/passwd',
    'gamex',
    'README.md',
    'gamex/./x',
    'docs/AGENTS.md',
  ])('rejects %s', (p) => {
    expect(() => {
      assertAllowedPath(p);
    }).toThrow(UnsafePathError);
  });
});
