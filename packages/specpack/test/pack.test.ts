import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PGlite } from '@electric-sql/pglite';
import { Validator } from '@seriousme/openapi-schema-validator';
import { Ajv2020 } from 'ajv/dist/2020.js';
import { beforeAll, describe, expect, it } from 'vitest';
import { parse as parseYaml } from 'yaml';
import { evalCurve, validateGameModel, type Curve } from '@gamex/model';
import { GENERATED_HEADER, renderSpecPack, type SpecPack } from '@gamex/specpack';
import { writeSpecPack } from '../src/node/index.ts';
import { runNode, swarmRescue, tempRepo } from './helpers.ts';

let pack: SpecPack;
let repo: string;
const file = (path: string): string => {
  const f = pack.files.get(path);
  if (f === undefined) throw new Error(`missing ${path}`);
  return f.content;
};

beforeAll(() => {
  pack = renderSpecPack(swarmRescue());
  repo = tempRepo();
  writeSpecPack(repo, pack);
}, 120000);

describe('renderSpecPack', () => {
  it('produces every file of the Spec Pack', () => {
    const paths = [...pack.files.keys()];
    for (const p of [
      'gamex/README.md',
      'gamex/game-model.json',
      'gamex/schema/game-model.schema.json',
      'gamex/schema/golden.schema.json',
      'gamex/schema/balance.schema.json',
      'gamex/balance/economy.json',
      'gamex/balance/ads.json',
      'gamex/balance/gameplay.json',
      'gamex/formulas/FORMULAS.md',
      'gamex/formulas/reference.ts',
      'gamex/state-machine.json',
      'gamex/STATE_MACHINE.md',
      'gamex/backend/openapi.yaml',
      'gamex/backend/data-model.sql',
      'gamex/backend/RULES.md',
      'gamex/tests/README.md',
      'gamex/tests/runner/interpreter.ts',
      'gamex/tests/runner/run-golden.ts',
      'gamex/tests/golden/action-revive.json',
      'gamex/tests/golden/placement-interstitial-after-victory.json',
      'gamex/tasks/001-wallet-and-ledger.md',
      'gamex/skills/gamex-change-balance/SKILL.md',
      'gamex/skills/gamex-run-sim/SKILL.md',
      'gamex/skills/gamex-implement-task/SKILL.md',
      'gamex/reports/latest-sim.md',
      'CLAUDE.md',
      'GEMINI.md',
    ]) {
      expect(paths).toContain(p);
    }
    expect(paths.filter((p) => !p.startsWith('gamex/'))).toEqual(['CLAUDE.md', 'GEMINI.md']);
  });

  it('is deterministic (same model ⇒ byte-identical files)', () => {
    const again = renderSpecPack(swarmRescue());
    expect([...again.files]).toEqual([...pack.files]);
  }, 120000);

  it('marks every generated file with the header', () => {
    for (const [path, f] of pack.files) {
      if (f.ownership === 'generated' || f.ownership === 'editable')
        expect(f.content, path).toContain('GENERATED BY GAMEX ENGINE');
    }
    expect(GENERATED_HEADER).toBe(
      'GENERATED BY GAMEX ENGINE — edit via the studio or the gamex CLI',
    );
  });

  it('writes a Game Model that validates (with zero issues) and matches its JSON Schema', () => {
    const text = file('gamex/game-model.json');
    expect(validateGameModel(text).issues).toEqual([]);
    const ajv = new Ajv2020({ strict: false });
    const validate = ajv.compile(JSON.parse(file('gamex/schema/game-model.schema.json')) as object);
    expect(validate(JSON.parse(text)), JSON.stringify(validate.errors)).toBe(true);
  });

  it('writes golden and balance files that match their JSON Schemas', () => {
    const ajv = new Ajv2020({ strict: false });
    const golden = ajv.compile(JSON.parse(file('gamex/schema/golden.schema.json')) as object);
    const balance = ajv.compile(JSON.parse(file('gamex/schema/balance.schema.json')) as object);
    for (const [path, f] of pack.files) {
      if (path.startsWith('gamex/tests/golden/'))
        expect(golden(JSON.parse(f.content)), `${path} ${JSON.stringify(golden.errors)}`).toBe(
          true,
        );
      if (path.startsWith('gamex/balance/'))
        expect(balance(JSON.parse(f.content)), `${path} ${JSON.stringify(balance.errors)}`).toBe(
          true,
        );
    }
  });

  it('writes a valid OpenAPI 3.1 document with one endpoint per action', async () => {
    const doc = parseYaml(file('gamex/backend/openapi.yaml')) as {
      openapi: string;
      paths: Record<string, unknown>;
    };
    const result = await new Validator().validate(doc);
    expect(result.errors ?? [], JSON.stringify(result.errors)).toEqual([]);
    expect(result.valid).toBe(true);
    expect(doc.openapi).toBe('3.1.0');
    expect(Object.keys(doc.paths)).toEqual(
      expect.arrayContaining([
        '/players/{playerId}/actions/revive',
        '/players/{playerId}/placements/interstitial-after-victory/eligibility',
        '/players/{playerId}/state',
      ]),
    );
    const revive = doc.paths['/players/{playerId}/actions/revive'] as {
      post: {
        responses: {
          '409': {
            content: {
              'application/json': { schema: { properties: { error: { enum: string[] } } } };
            };
          };
        };
      };
    };
    expect(
      revive.post.responses['409'].content['application/json'].schema.properties.error.enum,
    ).toEqual(['REVIVE_NOT_AVAILABLE', 'REVIVE_LIMIT_REACHED', 'PLACEMENT_NOT_ELIGIBLE']);
  });

  it('writes SQL that PostgreSQL accepts and that enforces the rules', async () => {
    const db = new PGlite();
    await db.exec(file('gamex/backend/data-model.sql'));
    await db.exec(`INSERT INTO "players" ("player_id") VALUES ('p1')`);
    await db.exec(`INSERT INTO "wallet" VALUES ('p1', 'coins', 10)`);
    await expect(db.exec(`INSERT INTO "wallet" VALUES ('p1', 'gems', 10)`)).rejects.toThrow();
    await expect(db.exec(`UPDATE "wallet" SET "amount" = -1`)).rejects.toThrow();
    await db.exec(`INSERT INTO "player_state" ("player_id") VALUES ('p1')`);
    const row = await db.query<{ highest_level_unlocked: number; selected_hero: string }>(
      `SELECT * FROM "player_state"`,
    );
    expect(row.rows[0]).toMatchObject({ highest_level_unlocked: 1, selected_hero: 'relickeeper' });
    await expect(db.exec(`UPDATE "player_state" SET "selected_hero" = 'nobody'`)).rejects.toThrow();
    await db.exec(
      `INSERT INTO "ad_claims" ("player_id", "placement", "network", "verification_token") VALUES ('p1', 'rewarded-revive', 'net', 't1')`,
    );
    await expect(
      db.exec(
        `INSERT INTO "ad_claims" ("player_id", "placement", "network", "verification_token") VALUES ('p1', 'rewarded-revive', 'net', 't1')`,
      ),
    ).rejects.toThrow();
    await db.close();
  }, 60000);

  it('keeps the AGENTS.md section short (30–60 lines) and states the core rules', () => {
    const lines = pack.agentsSection.split('\n').length;
    expect(lines).toBeGreaterThanOrEqual(30);
    expect(lines).toBeLessThanOrEqual(60);
    for (const rule of [
      'Never hardcode economy values',
      'gamex/balance',
      'openapi.yaml',
      'golden cases',
      'gamex sync',
    ])
      expect(pack.agentsSection).toContain(rule);
  });

  it('draws every screen in the Mermaid diagram', () => {
    const md = file('gamex/STATE_MACHINE.md');
    expect(md).toContain('stateDiagram-v2');
    for (const s of swarmRescue().stateMachine.states)
      expect(md).toContain(`${s.id.replaceAll('-', '_')}:`);
    expect(md).toContain('s21_pause --> s08_gameplay: ui');
  });

  it('writes balance files with every constant, grouped by balanceFile', () => {
    const ads = JSON.parse(file('gamex/balance/ads.json')) as {
      values: Record<string, number>;
      meta: Record<string, { status: string }>;
    };
    expect(ads.values).toMatchObject({
      interstitialMinGapSeconds: 180,
      interstitialMaxPerMission: 1,
      maxRevivesPerMission: 1,
    });
    expect(ads.meta['interstitialMinGapSeconds']?.status).toBe('confirmed');
    const economy = JSON.parse(file('gamex/balance/economy.json')) as {
      curves: Record<string, unknown>;
    };
    expect(Object.keys(economy.curves)).toEqual(['upgradeCost']);
  });

  it('orders tasks and makes each one done when its golden cases pass', () => {
    const tasks = [...pack.files.keys()].filter((p) => p.startsWith('gamex/tasks/'));
    expect(tasks.slice(0, 3)).toEqual([
      'gamex/tasks/001-wallet-and-ledger.md',
      'gamex/tasks/002-player-state.md',
      'gamex/tasks/003-rewarded-ad-verification.md',
    ]);
    expect(tasks.at(-1)).toMatch(/ad-pacing\.md$/);
    const revive = file(tasks.find((p) => p.endsWith('-revive.md')) ?? '');
    expect(revive).toMatch(/Acceptance\.\*\* Done when these golden cases pass.*`revive-001`/s);
    expect(revive).toContain('<!-- GAMEX:EDITABLE notes -->');
  });

  it('reports simulation results, invariants and exploration', () => {
    const report = file('gamex/reports/latest-sim.md');
    expect(report).toContain('✅ All invariants that were exercised hold.');
    expect(report).toContain('✅ No UI ad can appear in a forbidden screen.');
    expect(report).toContain('| interstitial-min-gap | trace | blocking | pass |');
    expect(report).toContain(pack.simulation.record.outputHash.slice(0, 16));
  });
});

describe('the pack in a repo', () => {
  it('runs every golden case with plain node and passes', () => {
    const { code, out } = runNode(repo, ['gamex/tests/runner/run-golden.ts']);
    expect(out).toMatch(/# \d+ passed, 0 failed/);
    expect(code).toBe(0);
    const total = pack.goldens.reduce((n, g) => n + g.cases.length, 0);
    expect(out).toContain(`1..${String(total)}`);
  }, 60000);

  it('ships a reference.ts whose curves match the engine', () => {
    writeFileSync(
      join(repo, 'check-reference.mjs'),
      "import { upgradeCost, constants, evaluateFormula } from './gamex/formulas/reference.ts';\nconsole.log(JSON.stringify({ costs: [1,2,3,4,5,10].map(upgradeCost), gap: constants.interstitialMinGapSeconds, f: evaluateFormula('curve(upgradeCost, damageTier + 1)', { damageTier: 2 }) }));\n",
    );
    const { code, out } = runNode(repo, ['check-reference.mjs']);
    expect(code).toBe(0);
    const curve = swarmRescue().constants.find((k) => k.id === 'upgrade-cost')?.value as Curve;
    const expected = [1, 2, 3, 4, 5, 10].map((n) => {
      const r = evalCurve(curve, n);
      return r.ok ? r.value : NaN;
    });
    expect(JSON.parse(out.trim().split('\n').at(-1) ?? '{}')).toEqual({
      costs: expected,
      gap: 180,
      f: 225,
    });
  }, 60000);

  it('the written game-model.json can be read back and re-synced without changes', () => {
    const text = readFileSync(join(repo, 'gamex/game-model.json'), 'utf8');
    const again = renderSpecPack(JSON.parse(text) as ReturnType<typeof swarmRescue>);
    const r = writeSpecPack(repo, again);
    expect(r.files.filter((f) => f.action !== 'unchanged' && f.action !== 'skip')).toEqual([]);
  }, 120000);
});
