import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { compileModel } from '@gamex/engine';
import { canonicalStringify, type GameModel } from '@gamex/model';
import { TEMPLATES } from '../src/templates.generated.ts';
import { generateGoldens } from '../src/golden/generate.ts';
import { readFileSync } from 'node:fs';

const swarm = JSON.parse(
  readFileSync(
    new URL('../../../fixtures/swarm-rescue/swarm-rescue.game-model.json', import.meta.url),
    'utf8',
  ),
) as GameModel;

function writePack(model: GameModel, goldenModel: GameModel = model): string {
  const dir = mkdtempSync(join(tmpdir(), 'gamex-pack-'));
  mkdirSync(join(dir, 'tests', 'golden'), { recursive: true });
  mkdirSync(join(dir, 'tests', 'runner'), { recursive: true });
  writeFileSync(join(dir, 'game-model.json'), canonicalStringify(model));
  for (const f of generateGoldens(compileModel(goldenModel)))
    writeFileSync(
      join(dir, 'tests', 'golden', `${f.subject.replace(':', '-')}.json`),
      canonicalStringify(f),
    );
  for (const [path, content] of Object.entries(TEMPLATES)) writeFileSync(join(dir, path), content);
  return dir;
}

function runGolden(dir: string): { code: number; out: string } {
  try {
    return {
      code: 0,
      out: execFileSync('node', [join(dir, 'tests', 'runner', 'run-golden.ts')], {
        cwd: dir,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      }),
    };
  } catch (error) {
    const e = error as { status: number; stdout: string };
    return { code: e.status, out: e.stdout };
  }
}

describe('the reference runner shipped in the pack', () => {
  it('passes every golden case generated by the engine (runner ≡ engine)', () => {
    const { code, out } = runGolden(writePack(swarm));
    expect(out).toMatch(/# \d+ passed, 0 failed/);
    expect(code).toBe(0);
  }, 60000);

  it('fails the affected golden cases when a rule changes (the tests have teeth)', () => {
    const changed = structuredClone(swarm);
    const k = changed.constants.find((c) => c.id === 'max-revives-per-mission');
    if (k) k.value = 2;
    const { code, out } = runGolden(writePack(changed, swarm));
    expect(code).toBe(1);
    expect(out).toMatch(/not ok \d+ - revive-\d{3}/);
    expect(out).not.toMatch(/not ok \d+ - (claim-triple|interstitial)/);
  }, 60000);
});
