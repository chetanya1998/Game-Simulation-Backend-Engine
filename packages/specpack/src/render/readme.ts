import type { GameModel } from '@gamex/model';
import { MD_HEADER, type FileMap } from './common.js';

export function renderReadmes(model: GameModel, files: FileMap): void {
  files.set('gamex/README.md', {
    ownership: 'generated',
    content: `${MD_HEADER}

# GameX Engine Spec Pack — ${model.meta.name}

This folder is the buildable, testable spec of the game's economy and rules. The source of truth is
[\`game-model.json\`](./game-model.json); everything else is generated from it by \`gamex sync\`.

| Path | What it is |
| --- | --- |
| \`game-model.json\` | The canonical Game Model (edit via the studio or by hand, then \`gamex validate\`). |
| \`schema/\` | JSON Schemas for the model, the balance files and the golden tests. |
| \`balance/*.json\` | Every tunable value. Game and backend code read these; never hardcode numbers. |
| \`formulas/FORMULAS.md\`, \`formulas/reference.ts\` | Every formula, readable and executable. |
| \`state-machine.json\`, \`STATE_MACHINE.md\` | Screens and transitions, with a Mermaid diagram. |
| \`backend/openapi.yaml\` | Economy API contract (OpenAPI 3.1). |
| \`backend/data-model.sql\` | PostgreSQL tables: wallet, ledger, state, ad claims, purchases, idempotency keys. |
| \`backend/RULES.md\` | Server-authoritative rules, error codes, anti-cheat (has editable sections). |
| \`tests/golden/\` | Given/when/then cases; \`tests/runner/\` runs them (\`node gamex/tests/runner/run-golden.ts\`). |
| \`tasks/\` | Ordered build tasks; each is done when its golden cases pass. |
| \`skills/\` | Agent skills (SKILL.md): change balance, run the simulation, implement a task. |
| \`reports/latest-sim.md\` | Latest simulation, invariants, findings and exploration results. |

## Regenerate

\`\`\`bash
gamex validate && gamex sync
\`\`\`

\`sync\` is idempotent (running it twice changes nothing) and never touches files outside \`gamex/\`, except the
delimited GameX section of \`AGENTS.md\` and the \`CLAUDE.md\`/\`GEMINI.md\` shims (created only if missing).
Files marked \`GENERATED BY GAMEX ENGINE\` are overwritten; if you edited one, \`sync\` stops and reports a
conflict (\`--force\` overwrites). Text inside \`GAMEX:EDITABLE\` regions is always kept. \`.gamex-lock.json\`
records what GameX last wrote.
`,
  });
  files.set('gamex/tests/README.md', {
    ownership: 'generated',
    content: `${MD_HEADER}

# Golden tests

Each file in \`golden/\` holds the cases for one action or placement:

\`\`\`json
{ "id": "revive-003", "rule": "rule:revive-limit-mission",
  "given": { "state": "s14-defeat", "vars": { "lastMissionResult": "defeat", "reviveCountMission": 1 } },
  "when":  { "action": "revive" },
  "then":  { "result": "rejected", "error": "REVIVE_LIMIT_REACHED", "deltas": {} } }
\`\`\`

- \`given.state\`, \`given.prevState\`, \`given.now\` (seconds) and \`given.vars\` (values by key that differ from the
  model's initial values) describe the player. Missing values take their initial value.
- \`when\` is an action (with the \`outcome\` for actions with random outcomes) or a placement eligibility check.
- \`then\` is the only correct result: \`result\`, \`error\` code, \`deltas\` (numbers: change; others: new value,
  keys sorted), \`impressions\` (placements shown) — or \`eligible\` and \`reason\` for placements.

Every expected result was computed by the GameX Engine rule interpreter — never by an AI.

## Running

\`\`\`bash
node gamex/tests/runner/run-golden.ts
\`\`\`

needs Node ≥ 22.18 and nothing else. It runs every case against \`runner/interpreter.ts\` (the executable
definition of the rules) and prints TAP; the exit code is 1 if any case fails.

## Testing your backend (any language)

Write an adapter that, for each case, sets your backend's state from \`given\`, performs \`when\`, and returns the
\`then\` your backend produced; compare it with the case's \`then\` (key order does not matter). In TypeScript,
replace \`run()\` in \`runner/run-golden.ts\`; in other languages, load the JSON files and do the same. A task in
\`../tasks/\` is done when every case it lists passes.
`,
  });
  files.set('gamex/.gitignore', {
    ownership: 'generated',
    content: '# GENERATED BY GAMEX ENGINE\n.work/\n',
  });
}
