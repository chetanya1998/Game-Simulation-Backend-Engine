import type { GameModel } from '@gamex/model';
import type { FileMap } from './common.js';

/** The body of the delimited GameX section in the target repo's AGENTS.md (≈40 lines). */
export function agentsSection(model: GameModel): string {
  return `## GameX Engine spec (${model.meta.name})

This repo's game economy and rules are specified in \`gamex/\`. The spec is generated from
\`gamex/game-model.json\` — never edit generated files by hand.

**Rules for coding agents**

1. Never hardcode economy values. Read them from \`gamex/balance/*.json\`.
2. Implement the backend against \`gamex/backend/openapi.yaml\`, \`gamex/backend/RULES.md\` and
   \`gamex/backend/data-model.sql\`. The server is authoritative for every balance and counter.
3. A task in \`gamex/tasks/\` is done only when the golden cases it lists pass
   (\`node gamex/tests/runner/run-golden.ts\` with your adapter — see \`gamex/tests/README.md\`).
4. Economy or rule changes go through the Game Model: edit \`gamex/game-model.json\` (or the studio),
   then run \`gamex validate\`, \`gamex sim\` and \`gamex sync\`, and review \`gamex/reports/latest-sim.md\`.
5. Do not edit files marked \`GENERATED BY GAMEX ENGINE\`; only the \`GAMEX:EDITABLE\` regions are yours.

**Commands**

- \`gamex validate\` — check the model (file, line and a fix for every problem).
- \`gamex sim\` / \`gamex explore\` — simulate players; search for unreachable screens and exploits.
- \`gamex sync\` — regenerate this spec (idempotent; stops if a generated file was edited by hand).

**Where things are**

- \`gamex/README.md\` — what each file is and how to regenerate.
- \`gamex/formulas/FORMULAS.md\` — every formula; \`gamex/formulas/reference.ts\` runs them.
- \`gamex/STATE_MACHINE.md\` — screens and transitions (Mermaid).
- \`gamex/tests/golden/\` — given/when/then cases; \`gamex/tests/runner/\` — the reference runner.
- \`gamex/skills/\` — skills: change balance, run the simulation, implement a task.
- \`gamex/reports/latest-sim.md\` — the latest simulation and exploration results.

Load detail files only when the current task needs them.`;
}

export function renderShims(files: FileMap): void {
  const shim = (name: string): string =>
    `# ${name}\n\nFollow [AGENTS.md](./AGENTS.md). Game economy rules: \`gamex/\` (see the GameX Engine section).\n`;
  files.set('CLAUDE.md', { ownership: 'create-if-missing', content: shim('CLAUDE.md') });
  files.set('GEMINI.md', { ownership: 'create-if-missing', content: shim('GEMINI.md') });
}
