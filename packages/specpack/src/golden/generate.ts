import { idToKey, parseExpr, walkExpr, type ExprValue } from '@gamex/model';
import {
  analyzeReachability,
  applyAction,
  availableOptions,
  checkAction,
  controlKey,
  createWorld,
  evalBool,
  evalNum,
  initialValues,
  perform,
  placementEligibility,
  settle,
  type CExpr,
  type CompiledModel,
  type WorldState,
} from '@gamex/engine';
import type { GoldenCase, GoldenFile } from './schema.js';

export const GENERATED_HEADER = 'GENERATED BY GAMEX ENGINE — edit via the studio or the gamex CLI';

interface Draft {
  readonly rule: string;
  readonly description: string;
  readonly world: WorldState;
  readonly when: GoldenCase['when'];
}

/** The given-part of a case: only values that differ from the model's initial values. */
function givenOf(c: CompiledModel, w: WorldState): GoldenCase['given'] {
  const initial = initialValues(c);
  const vars: Record<string, ExprValue> = {};
  for (const key of Object.keys(w.values).sort()) {
    const v = w.values[key];
    if (v !== undefined && v !== initial[key]) vars[key] = v;
  }
  return {
    state: w.state,
    ...(w.prevState === w.state ? {} : { prevState: w.prevState }),
    ...(w.now === 0 ? {} : { now: w.now }),
    vars,
  };
}

/** The expected result, computed only by the engine (the single enforcement path). */
function thenOf(c: CompiledModel, w: WorldState, when: GoldenCase['when']): GoldenCase['then'] {
  if ('placement' in when) {
    const p = c.placements.get(when.placement);
    if (p === undefined) throw new Error(`unknown placement ${when.placement}`);
    const e = placementEligibility(c, w, p);
    return e.reason === undefined
      ? { eligible: e.eligible }
      : { eligible: e.eligible, reason: e.reason };
  }
  const r = applyAction(c, w, when.action, {
    checkInvariants: false,
    ...(when.outcome === undefined ? {} : { outcome: when.outcome }),
  });
  const impressions = r.events.flatMap((e) => (e.type === 'impression' ? [e.placementId] : []));
  return {
    result: r.result,
    ...(r.error === undefined ? {} : { error: r.error.code }),
    ...(r.outcome === undefined ? {} : { outcome: r.outcome }),
    deltas: { ...r.deltas },
    ...(impressions.length === 0 ? {} : { impressions }),
  };
}

/**
 * Breadth-first search over concrete game states (screen + variables), returning for every action the first
 * state where it can run and for every screen-triggered placement the first state where it is eligible.
 */
function findBaseWorlds(
  c: CompiledModel,
  maxNodes: number,
): { actions: Map<string, WorldState>; placements: Map<string, WorldState> } {
  const actions = new Map<string, WorldState>();
  const placements = new Map<string, WorldState>();
  const want =
    c.actions.size + [...c.placements.values()].filter((p) => p.triggerState !== undefined).length;
  const note = (w: WorldState): void => {
    for (const a of c.actions.values())
      if (!actions.has(a.id) && checkAction(c, w, a.id).ok) actions.set(a.id, w);
    for (const p of c.statePlacements.get(w.state) ?? [])
      if (!placements.has(p.id) && placementEligibility(c, w, p).eligible) placements.set(p.id, w);
  };
  const start = settle(c, createWorld(c), { checkInvariants: false }).next;
  note(createWorld(c));
  note(start);
  const seen = new Set([controlKey(c, start)]);
  let frontier = [start];
  let nodes = 1;
  while (frontier.length > 0 && nodes < maxNodes && actions.size + placements.size < want) {
    const next: WorldState[] = [];
    for (const w of frontier) {
      for (const option of availableOptions(c, w)) {
        // The moment of entering a screen, before its placements are shown.
        const targets =
          option.kind === 'action' ? option.transitions.map((t) => t.to) : [option.transition.to];
        for (const to of targets)
          if (to !== 'return' && to !== w.state && c.statePlacements.has(to))
            note({ ...w, state: to, prevState: w.state });
        const action = option.kind === 'action' ? c.actions.get(option.actionId) : undefined;
        for (const outcome of action?.outcomes?.map((o) => o.id) ?? [undefined]) {
          let entered: WorldState;
          try {
            const r = perform(c, w, option, {
              checkInvariants: false,
              ...(outcome === undefined ? {} : { outcome }),
            });
            entered = r.next;
            note(entered);
            const settled = settle(c, entered, { checkInvariants: false }).next;
            // Jump time forward so cooldowns never hide a state (as in reachability).
            const n = { ...settled, now: settled.now + 1000 };
            note(n);
            const key = controlKey(c, n);
            if (seen.has(key)) continue;
            seen.add(key);
            nodes++;
            next.push(n);
          } catch {
            continue;
          }
        }
      }
    }
    frontier = next;
  }
  return { actions, placements };
}

/** Candidate values that might flip a condition: flips, other enum values, neighbours and range ends. */
function candidatesFor(c: CompiledModel, w: WorldState, key: string, expr: CExpr): ExprValue[] {
  const current = w.values[key];
  const variable = c.variables.get(key);
  if (typeof current === 'boolean') return [!current];
  if (typeof current === 'string')
    return (
      variable?.type === 'enum'
        ? (c.model.variables.find((v) => idToKey(v.id) === key)?.enumValues ?? [])
        : []
    ).filter((v) => v !== current);
  if (typeof current !== 'number') return [];
  const out = new Set<number>([current + 1, current - 1, 0]);
  if (variable?.min !== undefined) out.add(variable.min);
  if (variable?.max !== undefined) out.add(variable.max);
  // Numbers the expression compares against (constants and literals), and their neighbours.
  walkExpr(expr.ast, (n) => {
    if (n.kind === 'number') [n.value, n.value - 1, n.value + 1].forEach((x) => out.add(x));
    if (n.kind === 'ident') {
      const k = c.constants.get(n.name);
      if (k !== undefined) [k, k - 1, k + 1].forEach((x) => out.add(x));
    }
  });
  const isResource = c.resources.has(key);
  return [...out]
    .filter(
      (x) =>
        x !== current &&
        Number.isFinite(x) &&
        (!isResource || x >= 0) &&
        (variable?.type !== 'int' || Number.isInteger(x)),
    )
    .sort((a, b) => a - b);
}

function identifiers(expr: CExpr): string[] {
  const out = new Set<string>();
  walkExpr(expr.ast, (n) => {
    if (n.kind === 'ident') out.add(n.name);
  });
  return [...out];
}

function setValues(w: WorldState, values: Record<string, ExprValue>): WorldState {
  return { ...w, values: { ...w.values, ...values } };
}

/** Variations of `base` that make `expr` false while it was true (one variable changed at a time). */
function falsify(
  c: CompiledModel,
  base: WorldState,
  expr: CExpr,
  isTrue: (w: WorldState) => boolean,
): WorldState | undefined {
  for (const key of identifiers(expr)) {
    if (!(key in base.values)) continue;
    for (const v of candidatesFor(c, base, key, expr)) {
      const w = setValues(base, { [key]: v });
      try {
        if (!isTrue(w)) return w;
      } catch {
        continue;
      }
    }
  }
  return undefined;
}

function boolOf(c: CompiledModel, w: WorldState, e: CExpr): boolean {
  try {
    return evalBool(c, w, e);
  } catch {
    return false;
  }
}

export interface GoldenOptions {
  /** Upper bound on concrete states explored to find a starting state per action (default 20 000). */
  readonly maxNodes?: number;
  /** Cases taken from witness paths per action (default 2). */
  readonly pathCasesPerAction?: number;
}

/**
 * Generates golden cases for every action and screen-triggered placement:
 * - accepted cases (one per outcome) from the first reachable state where the action can run;
 * - boundary cases for each limit, cooldown and cost (just inside / just outside);
 * - one case per precondition, rule and eligibility condition that makes it fail;
 * - cases sampled along the shortest paths to every screen.
 * Every `then` is computed by the engine.
 */
export function generateGoldens(c: CompiledModel, options: GoldenOptions = {}): GoldenFile[] {
  const { actions: bases, placements: placementBases } = findBaseWorlds(
    c,
    options.maxNodes ?? 20000,
  );
  const files: GoldenFile[] = [];

  for (const a of c.actions.values()) {
    const base = bases.get(a.id);
    const drafts: Draft[] = [];
    if (base !== undefined) {
      for (const outcome of a.outcomes?.map((o) => o.id) ?? [undefined]) {
        drafts.push({
          rule: `action:${a.id}`,
          description: `${a.id} succeeds${outcome === undefined ? '' : ` with outcome "${outcome}"`}`,
          world: base,
          when: outcome === undefined ? { action: a.id } : { action: a.id, outcome },
        });
      }
      const when = {
        action: a.id,
        ...(a.outcomes?.[0] === undefined ? {} : { outcome: a.outcomes[0].id }),
      };
      a.preconditions.forEach((p, j) => {
        const w = falsify(c, base, p, (x) => boolOf(c, x, p));
        if (w !== undefined)
          drafts.push({
            rule: `action:${a.id}#precondition-${String(j)}`,
            description: `${a.id} is rejected when "${p.source}" is false`,
            world: w,
            when,
          });
      });
      for (const r of a.rules) {
        const derived = c.model.rules.find((x) => x.id === r.id)?.derivedFrom !== undefined;
        const limit = /^(\w+) < \((.*)\)$/.exec(r.expr.source);
        const cooldown = /^now - (\w+) >= \((.*)\)$/.exec(r.expr.source);
        if (derived && limit !== null) {
          const [, counter = '', maxSrc = ''] = limit;
          const max = evalNum(c, base, {
            ...r.expr,
            ast: (parseExpr(maxSrc) as { ok: true; value: CExpr['ast'] }).value,
          });
          drafts.push({
            rule: `rule:${r.id}`,
            description: `${a.id} is rejected once ${counter} reaches ${String(max)}`,
            world: setValues(base, { [counter]: max }),
            when,
          });
          if (max - 1 >= 0 && max - 1 !== base.values[counter])
            drafts.push({
              rule: `rule:${r.id}`,
              description: `${a.id} is still allowed at ${counter} = ${String(max - 1)}`,
              world: setValues(base, { [counter]: max - 1 }),
              when,
            });
        } else if (derived && cooldown !== null) {
          const [, lastAt = '', secSrc = ''] = cooldown;
          const seconds = evalNum(c, base, {
            ...r.expr,
            ast: (parseExpr(secSrc) as { ok: true; value: CExpr['ast'] }).value,
          });
          drafts.push({
            rule: `rule:${r.id}`,
            description: `${a.id} is rejected ${String(seconds - 1)} s after the last use`,
            world: setValues(base, { [lastAt]: base.now - seconds + 1 }),
            when,
          });
          drafts.push({
            rule: `rule:${r.id}`,
            description: `${a.id} is allowed exactly ${String(seconds)} s after the last use`,
            world: setValues(base, { [lastAt]: base.now - seconds }),
            when,
          });
        } else {
          const w = falsify(c, base, r.expr, (x) => boolOf(c, x, r.expr));
          if (w !== undefined)
            drafts.push({
              rule: `rule:${r.id}`,
              description: `${a.id} is rejected when "${r.expr.source}" is false`,
              world: w,
              when,
            });
        }
      }
      a.costs.forEach((cost, j) => {
        const amount = evalNum(c, base, cost.amount);
        drafts.push({
          rule: `action:${a.id}#cost-${String(j)}`,
          description: `${a.id} is allowed with exactly ${String(amount)} ${cost.key}`,
          world: setValues(base, { [cost.key]: amount }),
          when,
        });
        if (amount - 1 >= 0)
          drafts.push({
            rule: `action:${a.id}#cost-${String(j)}`,
            description: `${a.id} is rejected with ${String(amount - 1)} ${cost.key}`,
            world: setValues(base, { [cost.key]: amount - 1 }),
            when,
          });
      });
    }
    files.push(toFile(c, `action:${a.id}`, a.id, drafts));
  }

  for (const p of c.placements.values()) {
    if (p.triggerState === undefined) continue;
    const base = placementBases.get(p.id);
    const drafts: Draft[] = [];
    const when = { placement: p.id };
    if (base !== undefined) {
      drafts.push({
        rule: `placement:${p.id}`,
        description: `${p.id} is shown on entering ${p.triggerState}`,
        world: base,
        when,
      });
      const shows = (x: WorldState): boolean => placementEligibility(c, x, p).eligible;
      p.eligibility.forEach((e, j) => {
        const w = falsify(c, base, e, shows);
        if (w !== undefined)
          drafts.push({
            rule: `placement:${p.id}#eligibility-${String(j)}`,
            description: `${p.id} is not shown when "${e.source}" is false`,
            world: w,
            when,
          });
      });
      for (const r of p.rules) {
        const limit = /^(\w+) < \((.*)\)$/.exec(r.expr.source);
        const cooldown = /^now - (\w+) >= \((.*)\)$/.exec(r.expr.source);
        if (limit !== null) {
          const [, counter = '', maxSrc = ''] = limit;
          const max = evalNum(c, base, {
            ...r.expr,
            ast: (parseExpr(maxSrc) as { ok: true; value: CExpr['ast'] }).value,
          });
          drafts.push({
            rule: `rule:${r.id}`,
            description: `${p.id} is not shown once ${counter} reaches ${String(max)}`,
            world: setValues(base, { [counter]: max }),
            when,
          });
        } else if (cooldown !== null) {
          const [, lastAt = '', secSrc = ''] = cooldown;
          const seconds = evalNum(c, base, {
            ...r.expr,
            ast: (parseExpr(secSrc) as { ok: true; value: CExpr['ast'] }).value,
          });
          drafts.push({
            rule: `rule:${r.id}`,
            description: `${p.id} is not shown ${String(seconds - 1)} s after the last one`,
            world: setValues(base, { [lastAt]: base.now - seconds + 1 }),
            when,
          });
          drafts.push({
            rule: `rule:${r.id}`,
            description: `${p.id} is shown exactly ${String(seconds)} s after the last one`,
            world: setValues(base, { [lastAt]: base.now - seconds }),
            when,
          });
        } else {
          const w = falsify(c, base, r.expr, shows);
          if (w !== undefined)
            drafts.push({
              rule: `rule:${r.id}`,
              description: `${p.id} is not shown when "${r.expr.source}" is false`,
              world: w,
              when,
            });
        }
      }
      const forbidden = [...p.forbidden].sort();
      const s = forbidden.find((x) => c.states.get(x)?.kind === 'gameplay') ?? forbidden[0];
      if (!p.inWorld && s !== undefined)
        drafts.push({
          rule: `placement:${p.id}#forbidden`,
          description: `${p.id} is never shown in ${s}`,
          world: { ...base, state: s },
          when,
        });
    }
    files.push(toFile(c, `placement:${p.id}`, p.id, drafts));
  }

  addPathCases(c, files, options.pathCasesPerAction ?? 2);
  return files;
}

/** Adds cases sampled along the witness paths to every screen (realistic chains of play). */
function addPathCases(c: CompiledModel, files: GoldenFile[], perAction: number): void {
  const report = analyzeReachability(c);
  const taken = new Map<string, number>();
  for (const path of Object.values(report.witnesses)) {
    let w = settle(c, createWorld(c), { checkInvariants: false }).next;
    for (const step of path) {
      const option = availableOptions(c, w).find((o) =>
        step.action !== undefined
          ? o.kind === 'action' && o.actionId === step.action
          : o.kind !== 'action' && o.transition.id === step.transition,
      );
      if (option === undefined) break;
      if (option.kind === 'action' && (taken.get(option.actionId) ?? 0) < perAction) {
        const file = files.find((f) => f.subject === `action:${option.actionId}`);
        const when = {
          action: option.actionId,
          ...(step.outcome === undefined ? {} : { outcome: step.outcome }),
        };
        const given = givenOf(c, w);
        if (
          file !== undefined &&
          !file.cases.some(
            (x) =>
              JSON.stringify(x.given) === JSON.stringify(given) &&
              JSON.stringify(x.when) === JSON.stringify(when),
          )
        ) {
          file.cases.push({
            id: `${option.actionId}-${String(file.cases.length + 1).padStart(3, '0')}`,
            rule: `action:${option.actionId}#path`,
            description: `${option.actionId} on the way to ${path.at(-1)?.to ?? ''}`,
            given,
            when,
            then: thenOf(c, w, when),
          });
          taken.set(option.actionId, (taken.get(option.actionId) ?? 0) + 1);
        }
      }
      const r = perform(c, w, option, {
        checkInvariants: false,
        ...(step.outcome === undefined ? {} : { outcome: step.outcome }),
      });
      w = { ...settle(c, r.next, { checkInvariants: false }).next };
      w = { ...w, now: w.now + 1000 };
    }
  }
}

function toFile(
  c: CompiledModel,
  subject: string,
  id: string,
  drafts: readonly Draft[],
): GoldenFile {
  const seen = new Set<string>();
  const cases: GoldenCase[] = [];
  for (const d of drafts) {
    const given = givenOf(c, d.world);
    const key = JSON.stringify([given, d.when]);
    if (seen.has(key)) continue;
    seen.add(key);
    cases.push({
      id: `${id}-${String(cases.length + 1).padStart(3, '0')}`,
      rule: d.rule,
      description: d.description,
      given,
      when: d.when,
      then: thenOf(c, d.world, d.when),
    });
  }
  return { $comment: GENERATED_HEADER, subject, cases };
}
