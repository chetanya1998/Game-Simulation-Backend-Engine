function touches(a: Action, res: string, ops: readonly string[]): boolean {
  const effects = [...a.effects, ...(a.outcomes ?? []).flatMap((o) => o.effects)];
  return effects.some((e) => e.target === res && ops.includes(e.op));
}

/** One source → wallet → sink chain per resource, from the actions that change it. */
export function defaultFlows(model: GameModel): FlowNode[] {
  const out: FlowNode[] = [];
  const actionIds = new Set(model.actions.map((a) => a.id));
  for (const r of model.resources) {
    const res = `res:${r.id}`;
    const rewardActions = model.monetization.placements
      .filter(
        (p) =>
          'action' in p.trigger && (p.reward ?? []).some((e) => e.target === res && e.op === 'add'),
      )
      .map((p) => ('action' in p.trigger ? p.trigger.action : ''));
    const sources = [
      ...new Set([
        ...model.actions.filter((a) => touches(a, res, ['add'])).map((a) => `action:${a.id}`),
        ...rewardActions.filter((ref) => actionIds.has(ref.slice('action:'.length))),
      ]),
    ];
    const sinks = model.actions
      .filter((a) => a.costs.some((c) => c.resource === res) || touches(a, res, ['sub']))
      .map((a) => `action:${a.id}`);
    if (sources.length === 0 && sinks.length === 0) continue;
    const wallet = `${r.id}-wallet`;
    if (sources.length > 0) {
      out.push({
        id: `${r.id}-sources`,
        kind: 'source',
        resource: res,
        actions: sources,
        to: [`flow:${wallet}`],
        provenance: derived(`Actions that add ${r.name ?? r.id}.`),
      });
    }
    out.push({
      id: wallet,
      kind: 'pool',
      resource: res,
      actions: [],
      to: sinks.length > 0 ? [`flow:${r.id}-sinks`] : [],
      provenance: derived(`Player balance of ${r.name ?? r.id}.`),
    });
    if (sinks.length > 0) {
      out.push({
        id: `${r.id}-sinks`,
        kind: 'sink',
        resource: res,
        actions: sinks,
        to: [],
        provenance: derived(`Actions that spend ${r.name ?? r.id}.`),
      });
    }
  }
  return out;
}

/** Standard KPIs for what the model contains (resources, progression, ad formats, IAPs). */
export function defaultKpis(model: GameModel): Kpi[] {
  const out: Kpi[] = [];
  const kpi = (k: Omit<Kpi, 'provenance'>): void => {
    out.push({ ...k, provenance: derived('Standard KPI generated by GameX Engine.') });
  };
  const progress = model.variables.find(
    (v) =>
      v.scope === 'player' &&
      /level|stage|chapter/.test(v.id) &&
      (v.type === 'int' || v.type === 'number'),
  );
  if (progress !== undefined) {
    kpi({
      id: 'progression-speed',
      metric: 'progression-speed',
      params: { variable: `var:${progress.id}` },
    });
    const attempt = model.variables.find(
      (v) =>
        v.scope === 'mission' &&
        /level|stage/.test(v.id) &&
        (v.type === 'int' || v.type === 'number'),
    );
    kpi({
      id: 'progression-walls',
      metric: 'progression-walls',
      params: {
        variable: `var:${progress.id}`,
        ...(attempt === undefined ? {} : { attemptVariable: `var:${attempt.id}` }),
      },
    });
  }
  for (const r of model.resources) {
    kpi({ id: `${r.id}-balance`, metric: 'currency-balance', params: { resource: `res:${r.id}` } });
    kpi({ id: `${r.id}-inflation`, metric: 'inflation-rate', params: { resource: `res:${r.id}` } });
    kpi({
      id: `${r.id}-faucet-sink`,
      metric: 'faucet-sink-ratio',
      params: { resource: `res:${r.id}` },
    });
  }
  kpi({ id: 'churn-risk', metric: 'churn-risk' });
  const formats = [...new Set(model.monetization.placements.map((p) => p.format))].filter(
    (f) => f !== 'iap',
  );
  for (const f of formats)
    kpi({ id: `${f}-per-dau`, metric: 'ad-impressions-per-dau', params: { format: f } });
  if (formats.includes('rewarded')) kpi({ id: 'rewarded-opt-in', metric: 'rewarded-opt-in-rate' });
  for (const p of model.monetization.placements.filter((x) => x.format === 'iap')) {
    kpi({
      id: `${p.id}-conversion`,
      metric: 'iap-conversion',
      params: { placement: `placement:${p.id}` },
    });
  }
  return out;
}
