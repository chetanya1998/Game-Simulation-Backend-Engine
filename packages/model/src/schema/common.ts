import { z } from 'zod';
import { MAX_ID_LENGTH } from '../ids.js';

const ID_SOURCE = '[a-z][a-z0-9]*(?:-[a-z0-9]+)*';

export const IdSchema = z
  .string()
  .max(MAX_ID_LENGTH, { message: `ids are at most ${String(MAX_ID_LENGTH)} characters` })
  .regex(new RegExp(`^${ID_SOURCE}$`), {
    message:
      'ids must be kebab-case: lowercase letters and digits separated by single hyphens, starting with a letter (e.g. "max-revives-per-mission")',
  });

/** Prefixes of typed references (`const:interstitial-min-gap-seconds`). */
export const REF_PREFIXES = {
  entity: 'ent',
  resource: 'res',
  constant: 'const',
  variable: 'var',
  action: 'action',
  rule: 'rule',
  state: 'state',
  transition: 'transition',
  flow: 'flow',
  placement: 'placement',
  persona: 'persona',
  kpi: 'kpi',
  invariant: 'inv',
  gap: 'gap',
} as const;

export type RefKind = keyof typeof REF_PREFIXES;
export type RefPrefix = (typeof REF_PREFIXES)[RefKind];

export const ANY_REF_PATTERN = new RegExp(
  `^(${Object.values(REF_PREFIXES).join('|')}):(${ID_SOURCE})$`,
);

export function refSchema(...kinds: RefKind[]) {
  const prefixes = kinds.map((k) => REF_PREFIXES[k]);
  const example = `${prefixes[0] ?? 'const'}:some-id`;
  return z.string().regex(new RegExp(`^(?:${prefixes.join('|')}):${ID_SOURCE}$`), {
    message: `expected a reference of the form "${prefixes.map((p) => `${p}:<id>`).join('" or "')}", e.g. "${example}"`,
  });
}

export const ExprSchema = z.string().min(1, { message: 'expression is empty' });

export const ErrorCodeSchema = z.string().regex(/^[A-Z][A-Z0-9_]*$/, {
  message: 'error codes are UPPER_SNAKE_CASE, e.g. "REVIVE_LIMIT_REACHED"',
});

export const ProbabilitySchema = z.number().min(0).max(1);

export const ProvenanceSchema = z.strictObject({
  /** Repo-relative path, or "gamex:assumed" / "gamex:derived". */
  source: z.string().min(1),
  /** "§4.2 / lines 88–94", "p.7", "Assets/Tuning/Economy.asset:L14". */
  location: z.string(),
  excerpt: z.string().max(200, { message: 'excerpts are at most 200 characters' }),
  confidence: z.enum(['high', 'medium', 'low']),
  status: z.enum(['detected', 'confirmed', 'edited', 'assumed']),
  /** Conflicting evidence (e.g. GDD prose vs code), kept instead of silently resolved. */
  alternatives: z
    .array(
      z.strictObject({
        source: z.string().min(1),
        location: z.string(),
        excerpt: z.string().max(200),
        value: z.union([z.number(), z.string(), z.boolean()]).optional(),
      }),
    )
    .optional(),
});

/** Fields shared by every node. */
export const nodeBase = {
  id: IdSchema,
  /** camelCase key derived from the id; optional in files, filled in by the normalizer. */
  key: z.string().optional(),
  name: z.string().optional(),
  description: z.string().optional(),
  tags: z.array(z.string()).optional(),
  /** Set on nodes generated by the normalizer, pointing to their origin (e.g. "action:revive"). */
  derivedFrom: z.string().optional(),
  provenance: ProvenanceSchema,
};

export const EffectSchema = z.strictObject({
  op: z.enum(['set', 'add', 'sub']),
  target: refSchema('variable', 'resource'),
  value: ExprSchema,
});

export const ScopeSchema = z.enum(['mission', 'session', 'day', 'lifetime']);

export const LimitSchema = z.strictObject({
  max: ExprSchema,
  per: ScopeSchema,
  errorCode: ErrorCodeSchema.optional(),
});
